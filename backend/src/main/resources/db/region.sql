-- 区域表（省市区）
CREATE TABLE IF NOT EXISTS sys_region (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    region_code VARCHAR(10) NOT NULL COMMENT '区域编码(国标码)',
    region_name VARCHAR(50) NOT NULL COMMENT '区域名称',
    parent_code VARCHAR(10) COMMENT '父级编码',
    level INT NOT NULL COMMENT '层级: 1-省 2-市 3-区',
    sort INT DEFAULT 0 COMMENT '排序',
    status INT DEFAULT 1 COMMENT '状态 0-禁用 1-启用',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted INT DEFAULT 0,
    UNIQUE KEY uk_region_code (region_code),
    KEY idx_parent_code (parent_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='区域表';

-- 修改地址表字段
ALTER TABLE user_address CHANGE COLUMN province province_code VARCHAR(10) COMMENT '省份编码';
ALTER TABLE user_address CHANGE COLUMN city city_code VARCHAR(10) COMMENT '城市编码';
ALTER TABLE user_address CHANGE COLUMN district district_code VARCHAR(10) COMMENT '区县编码';

